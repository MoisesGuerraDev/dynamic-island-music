// What the clipboard history must never keep.
// Three layers: (1) the "do not record" flags the system and password managers put on the clipboard,
// (2) the app that copied it, (3) text that looks like a key, token or card number.

/** Clipboard formats that mean "do not store this". Present on the clipboard => ignore. */
export const WIN_SECRET_FORMATS = [
  'ExcludeClipboardContentFromMonitorProcessing', // set by Windows-aware password managers (1Password, Bitwarden, ...)
  'Clipboard Viewer Ignore', // set by KeePass and others
];

export const MAC_SECRET_FORMATS = [
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
  'com.agilebits.onepassword',
];

/** Process names (lowercase, no ".exe") of the copying app that we skip. Matches by substring. */
export function isIgnoredApp(processName, ignored) {
  const p = String(processName || '').toLowerCase().replace(/\.exe$/, '');
  if (!p) return false;
  return (ignored || []).some((x) => {
    const n = String(x).trim().toLowerCase().replace(/\.exe$/, '');
    return n && p.includes(n);
  });
}

const TOKEN_PATTERNS = [
  /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
  /^eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{4,}$/, // JWT
  /^sk-[A-Za-z0-9_-]{20,}$/, // OpenAI and Anthropic keys
  /^(ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}$/,
  /^github_pat_[A-Za-z0-9_]{30,}$/,
  /^AKIA[0-9A-Z]{16}$/, // AWS access key id
  /^AIza[0-9A-Za-z_-]{35}$/, // Google API key
  /^xox[abprs]-[A-Za-z0-9-]{10,}$/, // Slack
  /^(Bearer|Basic)\s+[A-Za-z0-9._~+/=-]{16,}$/,
  /^[a-f0-9]{64}$/i, // 256-bit hex secret (also a SHA-256, but not worth keeping)
];

function luhn(digits) {
  let sum = 0;
  let alt = false;
  for (let i = digits.length - 1; i >= 0; i--) {
    let n = digits.charCodeAt(i) - 48;
    if (alt) {
      n *= 2;
      if (n > 9) n -= 9;
    }
    sum += n;
    alt = !alt;
  }
  return sum % 10 === 0;
}

/** True when the text looks like a secret. Conservative on purpose: a normal sentence or URL never matches. */
export function looksSecret(text) {
  const t = String(text ?? '').trim();
  if (!t) return false;
  if (TOKEN_PATTERNS.some((re) => re.test(t))) return true;

  const compact = t.replace(/[\s-]/g, '');
  if (/^\d{13,19}$/.test(compact) && /^[\d\s-]+$/.test(t) && luhn(compact)) return true;

  // A single word with upper, lower, a digit and a symbol like !@#$ is almost always a password.
  if (t.length >= 10 && t.length <= 64 && !/\s/.test(t) && !/^[a-z]+:\/\//i.test(t) && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(t) && !/[\\/]/.test(t)) {
    const classes = [/[a-z]/, /[A-Z]/, /\d/, /[!@#$%^&*()+=?{}[\]<>~]/].filter((re) => re.test(t)).length;
    if (classes === 4) return true;
  }
  return false;
}

export function classifyText(text) {
  const t = String(text).trim();
  const isLink = !/\s/.test(t) && /^https?:\/\/\S+$/i.test(t);
  return isLink ? 'link' : 'text';
}
