import AppKit
import Combine
import Defaults
import SwiftUI

struct ClipItem: Identifiable, Equatable, Codable {
    enum Kind: String, Codable { case text, link, image }
    var id = UUID()
    var kind: Kind
    var text: String
    var imageData: Data?
    var date = Date()
    var app: String
}

/// Clipboard history. It ignores password managers and anything macOS marks as secret.
@MainActor
final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()

    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var toast: ClipItem?

    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var toastTask: Task<Void, Never>?

    private init() {
        load()
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard Defaults[.clipEnabled], !Defaults[.clipPaused] else { return }

        let types = (pb.types ?? []).map(\.rawValue)
        let secret = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        if types.contains(where: { secret.contains($0) }) { return }

        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, Defaults[.clipIgnoredApps].contains(id) { return }
        let appName = front?.localizedName ?? "—"

        var item: ClipItem?
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !t.contains(" ") && !t.contains("\n") && (URL(string: t)?.scheme?.hasPrefix("http") ?? false)
            item = ClipItem(kind: isLink ? .link : .text, text: String(t.prefix(2000)), app: appName)
        } else if let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
                  let png = rep.representation(using: .png, properties: [:]) {
            item = ClipItem(kind: .image, text: "Imagen \(Int(img.size.width)) × \(Int(img.size.height))", imageData: png.count < 3_000_000 ? png : nil, app: appName)
        }
        guard let item else { return }
        items.removeAll { $0.kind != .image && $0.text == item.text && $0.kind == item.kind }
        items.insert(item, at: 0)
        prune()
        save()
        showToast(item)
    }

    private func showToast(_ item: ClipItem) {
        guard Defaults[.clipToast] else { return }
        toast = item
        toastTask?.cancel()
        toastTask = Task {
            try? await Task.sleep(for: .seconds(2.2))
            if !Task.isCancelled { toast = nil }
        }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if item.kind == .image, let d = item.imageData, let img = NSImage(data: d) {
            pb.writeObjects([img])
        } else {
            pb.setString(item.text, forType: .string)
        }
        lastCount = pb.changeCount
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items = []
        save()
    }

    private func prune() {
        let max = Swift.max(5, Defaults[.clipMax])
        if items.count > max { items = Array(items.prefix(max)) }
        let days = Defaults[.clipAutoDeleteDays]
        if days > 0 { items.removeAll { Date().timeIntervalSince($0.date) > Double(days) * 86_400 } }
    }

    // MARK: Disk (text only, optional)

    private var fileURL: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("clipboard.json")
    }

    private func load() {
        guard Defaults[.clipPersist], let data = try? Data(contentsOf: fileURL),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = saved
        prune()
    }

    private func save() {
        guard Defaults[.clipPersist] else {
            try? FileManager.default.removeItem(at: fileURL)
            return
        }
        let textOnly = items.filter { $0.kind != .image }
        if let data = try? JSONEncoder().encode(textOnly) { try? data.write(to: fileURL, options: .atomic) }
    }
}

// MARK: - Views

struct ClipboardComponentView: View {
    @ObservedObject var clip = ClipboardManager.shared

    var body: some View {
        VStack(alignment: .leading, spacing: 5) {
            Label("Portapapeles", systemImage: "doc.on.clipboard").font(.system(size: 12, weight: .semibold))
            ForEach(clip.items.prefix(3)) { item in
                Button { clip.copy(item) } label: {
                    Text(item.text)
                        .font(.system(size: 11))
                        .foregroundStyle(.white.opacity(0.9))
                        .lineLimit(1)
                        .frame(maxWidth: .infinity, alignment: .leading)
                        .padding(.horizontal, 8).padding(.vertical, 5)
                        .background(Color.white.opacity(0.08), in: RoundedRectangle(cornerRadius: 8, style: .continuous))
                }
                .buttonStyle(.plain)
            }
            if clip.items.isEmpty {
                Text("Lo que copies aparecerá aquí.").font(.system(size: 11)).foregroundStyle(.gray)
            }
            Spacer(minLength: 0)
        }
        .padding(.top, 8)
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
    }
}

struct ClipboardTabView: View {
    @ObservedObject var clip = ClipboardManager.shared
    @State private var copiedID: UUID?

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack(spacing: 8) {
                Text("Portapapeles").font(.system(size: 14, weight: .semibold))
                Text("Ignora contraseñas y datos ocultos")
                    .font(.system(size: 10.5, weight: .medium))
                    .padding(.horizontal, 8).padding(.vertical, 3)
                    .islandGlass(Capsule(), interactive: false)
                Spacer()
                Text("\(clip.items.count) elementos").font(.system(size: 11)).foregroundStyle(.gray)
                GlassCircleButton(symbol: Defaults[.clipPaused] ? "play.fill" : "pause.fill", size: 28) {
                    Defaults[.clipPaused].toggle()
                }
                GlassCircleButton(symbol: "trash", size: 28) { clip.clear() }
            }
            if clip.items.isEmpty {
                Text("Todavía no hay nada. Copia algo y aparecerá aquí.").font(.system(size: 12)).foregroundStyle(.gray)
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollView {
                    LazyVGrid(columns: [GridItem(.flexible(), spacing: 6), GridItem(.flexible(), spacing: 6)], spacing: 6) {
                        ForEach(clip.items.prefix(30)) { item in
                            Button {
                                clip.copy(item)
                                copiedID = item.id
                                DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { if copiedID == item.id { copiedID = nil } }
                            } label: {
                                HStack(spacing: 8) {
                                    if item.kind == .image, let d = item.imageData, let img = NSImage(data: d) {
                                        Image(nsImage: img).resizable().scaledToFill().frame(width: 26, height: 26).clipShape(RoundedRectangle(cornerRadius: 5))
                                    } else {
                                        Text(item.kind == .link ? "ENLACE" : "TEXTO")
                                            .font(.system(size: 9, weight: .bold, design: .monospaced))
                                            .foregroundStyle(Color(red: 1, green: 0.7, blue: 0.55))
                                            .frame(width: 44, alignment: .leading)
                                    }
                                    Text(item.text).font(.system(size: 11.5)).lineLimit(1).foregroundStyle(.white)
                                    Spacer(minLength: 0)
                                    Text(copiedID == item.id ? "Copiado" : item.app)
                                        .font(.system(size: 10)).foregroundStyle(copiedID == item.id ? .green : .gray).lineLimit(1)
                                }
                                .padding(.horizontal, 10).padding(.vertical, 7)
                                .background(Color.white.opacity(0.07), in: RoundedRectangle(cornerRadius: 11, style: .continuous))
                            }
                            .buttonStyle(.plain)
                            .contextMenu { Button("Quitar", role: .destructive) { clip.remove(item) } }
                        }
                    }
                }
            }
        }
        .padding(.top, 4)
    }
}

/// Short notice below the closed notch when something is copied.
struct ClipboardToast: View {
    let item: ClipItem
    var body: some View {
        HStack(spacing: 8) {
            Text("COPIADO").font(.system(size: 9.5, weight: .bold, design: .monospaced)).foregroundStyle(Color(red: 1, green: 0.7, blue: 0.55))
            Text(item.text).font(.system(size: 12)).lineLimit(1).foregroundStyle(.white)
        }
        .frame(maxWidth: 360)
        .padding(.horizontal, 14).padding(.vertical, 7)
        .islandGlass(Capsule(), interactive: false)
        .transition(.opacity.combined(with: .move(edge: .top)))
    }
}
